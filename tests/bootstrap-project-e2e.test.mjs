import assert from "node:assert/strict";
import { access, cp, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const sourceRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));

const config = {
  projectName: "Disposable Bootstrap Project",
  slug: "pagechime",
  purpose: "Exercise Agent Project Starter bootstrap end to end",
  primaryUsers: "Test users",
  repository: "dn-lx/disposable-bootstrap-project",
  ownerTeam: "dn-lx",
  branches: { integration: "develop", production: "main" },
  architecture: {
    frontend: "React Native / Expo",
    backend: "Supabase Edge Functions",
    database: "PostgreSQL",
    authentication: "Supabase Auth",
    boundaries:
      "Client calls authenticated APIs; privileged logic stays server-side",
  },
  commands: {
    install: "npm ci",
    dev: "npm run dev",
    test: "node --test",
    build: "npm run build",
    lint: "npm run lint",
  },
  paths: {
    app: "apps/mobile",
    tests: "tests",
    database: "supabase",
  },
  capabilities: {
    sourceControl: {
      status: "Required",
      provider: "GitHub",
      purpose: "Source control and CI",
    },
    database: {
      status: "Required",
      provider: "Supabase",
      purpose: "Auth, database and server-side functions",
    },
  },
};

function run(root, args) {
  return execFileSync(process.execPath, args, {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
}

test("full starter copy bootstraps and passes strict validation", async () => {
  const tempRoot = await mkdtemp(join(tmpdir(), "agent-starter-e2e-"));
  const projectRoot = join(tempRoot, "project");

  await cp(sourceRoot, projectRoot, {
    recursive: true,
    filter: (source) =>
      !source
        .split(/[\\/]/)
        .some((x) =>
          [".git", "node_modules", ".next", "out", "dist", "books"].includes(x),
        ),
  });

  // A copied active project task is not part of this disposable bootstrap fixture.
  await writeFile(join(projectRoot, "docs/CURRENT-HANDOFF.md"), "# Current Handoff\n\n<!-- AGENT_TASK_STATE_START -->\n{\"task_id\":null,\"repository\":null,\"base\":\"develop\",\"branch\":null,\"pr\":null,\"status\":\"idle\",\"last_verified_sha\":null,\"next_step\":null,\"updated_at\":\"2026-10-24T00:00:00Z\"}\n<!-- AGENT_TASK_STATE_END -->\n", "utf8");

  const configPath = join(projectRoot, "bootstrap.e2e.json");
  await writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`, "utf8");

  const bootstrapOutput = run(projectRoot, [
    "scripts/bootstrap-project.mjs",
    "--config",
    "bootstrap.e2e.json",
  ]);
  assert.match(bootstrapOutput, /Updated \d+ bootstrap targets/);

  const syncOutput = run(projectRoot, [
    "scripts/sync-claude-skills.mjs",
    "--write",
  ]);
  assert.match(syncOutput, /Claude skill adapters valid:/);

  // The consuming project already has its identity and requirements.
  assert.match(
    run(projectRoot, ["scripts/validate-docs.mjs", "--strict-project"]),
    /Documentation valid:/,
  );

  await writeFile(
    join(projectRoot, "README.md"),
    "# Disposable Bootstrap Project\n\nA test project created from Agent Project Starter.\n",
    "utf8",
  );
  await writeFile(
    join(projectRoot, "docs/REQUIREMENTS.md"),
    "# Requirements\n\n## REQ-001 — Bootstrap\n\nThe generated project passes strict validation.\n",
    "utf8",
  );

  const docsOutput = run(projectRoot, [
    "scripts/validate-docs.mjs",
    "--strict-project",
  ]);
  assert.match(docsOutput, /Documentation valid:/);

  const stackOutput = run(projectRoot, ["scripts/validate-agent-stack.mjs"]);
  assert.match(stackOutput, /Core agent stack valid:/);
  assert.match(stackOutput, /branch policy develop → main/);

  const policy = JSON.parse(
    await readFile(join(projectRoot, ".agents/project-policy.json"), "utf8"),
  );
  assert.equal(policy.branches.integration, "develop");
  assert.equal(policy.branches.production, "main");

  const memory = await readFile(
    join(projectRoot, "docs/PROJECT-MEMORY.md"),
    "utf8",
  );
  assert.match(memory, /Disposable Bootstrap Project/);
  assert.match(memory, /Supabase Edge Functions/);

  const skill = await readFile(
    join(projectRoot, ".agents/skills/pagechime/SKILL.md"),
    "utf8",
  );
  assert.match(skill, /name: pagechime/);

  const adapter = await readFile(
    join(projectRoot, ".claude/skills/pagechime/SKILL.md"),
    "utf8",
  );
  assert.match(adapter, /Generated by scripts\/sync-claude-skills\.mjs/);

  await assert.rejects(
    access(join(projectRoot, ".agents/skills/project-template/SKILL.md")),
  );
  await assert.rejects(
    access(join(projectRoot, ".claude/skills/project-template/SKILL.md")),
  );
});
